"""
Core Domain Primitives and Evidence Contracts for TRACE.

This module provides the foundational value objects and primitive contracts
for capturing observable execution events from autonomous Large Language Model (LLM)
agents during task execution.

Pipeline Phase:
    ObservableEvidence -> BehaviourTrace -> BehaviourVector -> BehaviourProfile
    -> BehaviourConfidence -> BehaviourSignature -> TRACE Score
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, Optional
from pydantic import BaseModel, ConfigDict, Field, field_validator


class EventCategory(str, Enum):
    """Supported categories for observable execution events in TRACE."""

    REASONING = "reasoning"
    PLANNING = "planning"
    MEMORY = "memory"
    TOOL_USE = "tool_use"
    ENVIRONMENT = "environment"
    ACTION = "action"
    SYSTEM = "system"


class ObservableEvidence(BaseModel):
    """
    Represents an immutable single observable execution event generated by an LLM agent.

    Serves as the primitive data contract captured in the Evidence Acquisition Layer
    without modifying or interfering with the underlying agent architecture.
    """

    model_config = ConfigDict(
        frozen=True,
        extra="forbid",
        str_strip_whitespace=True,
        validate_assignment=True,
    )

    event_id: str = Field(
        ...,
        description="Unique identifier for the execution event.",
        min_length=1,
    )
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC timestamp marking when the event occurred.",
    )
    category: EventCategory = Field(
        ...,
        description="Functional category of the execution event.",
    )
    action_name: str = Field(
        ...,
        description="Specific operation or action performed (e.g., 'search_db', 'thought_step').",
        min_length=1,
    )
    payload: Dict[str, Any] = Field(
        default_factory=dict,
        description="Contextual evidence payload (inputs, outputs, intermediate thoughts, tool response).",
    )
    latency_ms: Optional[float] = Field(
        default=None,
        description="Duration of the action execution in milliseconds, if applicable.",
        ge=0.0,
    )
    is_error: bool = Field(
        default=False,
        description="Flag indicating if the execution event resulted in an error or exception.",
    )
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Additional execution context or environmental tags.",
    )

    @field_validator("timestamp")
    @classmethod
    def ensure_utc(cls, v: datetime) -> datetime:
        """Enforce that all timestamps explicitly hold timezone context."""
        if v.tzinfo is None:
            return v.replace(tzinfo=timezone.utc)
        return v.astimezone(timezone.utc)

    def to_dict(self) -> Dict[str, Any]:
        """Convert evidence instance to a dictionary representation."""
        return self.model_dump(mode="json")