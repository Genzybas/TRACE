"""
BehaviouralSignature and TRACE Score Engine.

Synthesizes BehaviourProfiles and Behavioural Confidence into diagnostic
BehaviouralSignature instances and confidence-adjusted overall TRACE Scores.

Manuscript Definitions:
    BS = (C, O, R, \kappa)
    \mathbf{W} = (\alpha, \beta, \gamma) where \alpha + \beta + \gamma = 1
    S_{\mathrm{TRACE}} = \alpha * C + \beta * O + \gamma * R
    S_{\mathrm{Final}} = \kappa * S_{\mathrm{TRACE}}
"""

from typing import Dict, Any, Optional
from pydantic import BaseModel, ConfigDict, Field, field_validator

from trace_eval.domain.profile import BehaviourProfile


class GlobalCategoryWeights(BaseModel):
    """
    Category importance weighting vector \mathbf{W} = (\alpha, \beta, \gamma).
    Enforces \alpha + \beta + \gamma = 1.0.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    alpha: float = Field(default=0.4, ge=0.0, le=1.0, description=r"Weight \alpha for Cognitive (C)")
    beta: float = Field(default=0.3, ge=0.0, le=1.0, description=r"Weight \beta for Operational (O)")
    gamma: float = Field(default=0.3, ge=0.0, le=1.0, description=r"Weight \gamma for Reliability (R)")

    @field_validator("gamma")
    @classmethod
    def validate_weights_sum(cls, v: float, info) -> float:
        alpha = info.data.get("alpha", 0.4)
        beta = info.data.get("beta", 0.3)
        total = alpha + beta + v
        if abs(total - 1.0) > 1e-6:
            raise ValueError(f"Category weights (\\alpha, \\beta, \\gamma) must sum to 1.0, got {total}")
        return v


class BehaviourSignature(BaseModel):
    """
    Final diagnostic representation generated by TRACE combining category scores
    and assessment confidence.
    """

    model_config = ConfigDict(
        frozen=True,
        extra="forbid",
        validate_assignment=True,
    )

    agent_id: str = Field(..., description="ID of evaluated agent.", min_length=1)
    cognitive: float = Field(..., ge=0.0, le=1.0, description="Cognitive score C")
    operational: float = Field(..., ge=0.0, le=1.0, description="Operational score O")
    reliability: float = Field(..., ge=0.0, le=1.0, description="Reliability score R")
    confidence: float = Field(..., gt=0.0, le=1.0, description=r"Behavioural Confidence \kappa")

    @classmethod
    def create(
        cls,
        profile: BehaviourProfile,
        confidence: float,
    ) -> "BehaviourSignature":
        """Factory method building BehaviourSignature from a BehaviourProfile and \kappa."""
        return cls(
            agent_id=profile.agent_id,
            cognitive=profile.cognitive,
            operational=profile.operational,
            reliability=profile.reliability,
            confidence=confidence,
        )

    def compute_trace_score(
        self,
        weights: Optional[GlobalCategoryWeights] = None,
    ) -> float:
        """
        Compute aggregate raw TRACE Score: S_{TRACE} = \alpha C + \beta O + \gamma R.
        """
        w = weights or GlobalCategoryWeights()
        return max(
            0.0,
            min(
                1.0,
                w.alpha * self.cognitive + w.beta * self.operational + w.gamma * self.reliability,
            ),
        )

    def compute_final_score(
        self,
        weights: Optional[GlobalCategoryWeights] = None,
    ) -> float:
        """
        Compute confidence-aware final score: S_{Final} = \kappa * S_{TRACE}.
        """
        s_trace = self.compute_trace_score(weights)
        return max(0.0, min(1.0, self.confidence * s_trace))

    def to_dict(self) -> Dict[str, Any]:
        """Serialize signature and computed score metrics to dict."""
        s_trace = self.compute_trace_score()
        s_final = self.compute_final_score()
        return {
            "agent_id": self.agent_id,
            "signature": {
                "C": self.cognitive,
                "O": self.operational,
                "R": self.reliability,
                "kappa": self.confidence,
            },
            "S_TRACE": s_trace,
            "S_Final": s_final,
        }